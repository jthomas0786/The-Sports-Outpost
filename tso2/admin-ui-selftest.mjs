import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=p=>fs.readFileSync(p,'utf8');
const html=read('tso2/index.html');
const app=read('tso2/app.js');
const pages=read('tso2/pages.js');
const admin=read('tso2/admin.js');
const auth=read('tso2/auth.js');
const css=read('tso2/styles.css');
assert.match(html,/data-admin-open hidden/,'Owner admin menu starts hidden');
assert.match(html,/data-owner-only data-admin-open/,'Admin navigation requires verified owner');
assert.match(html,/src="\.\/admin\.js/,'Admin script included in app');
assert.match(html,/data-tso2-public-notice/,'Public notice has a mount point');
assert.match(app,/admin:'Admin Control Room'/,'Admin route exists');
assert.match(app,/if\(route==='admin'&&!isOwner\(\)\)/,'Guest cannot navigate to Admin');
assert.match(app,/if\(currentRoute==='admin'\)\{\s*if\(!isOwner\(\)\) setRoute\('home'\)/,'Sign-out leaves Admin');
assert.match(app,/window\.TSO2Admin\?\.mount/,'Admin route connects dashboard');
assert.match(pages,/admin\(\)\{/,'Admin dashboard page is present');
assert.match(pages,/window\.TSO_AUTH\?\.user\?\.isOwner!==true/,'Guest page renders only a locked screen');
assert.match(auth,/client\.rpc\(name,args\)/,'RPC calls use the existing authenticated Supabase client');
assert.match(admin,/tso2_admin_get_dashboard/,'Admin reports from server');
assert.match(admin,/tso2_admin_save_settings/,'Settings saves from server');
assert.match(admin,/tso2_get_public_notice/,'Public announcement backed by database');
assert.doesNotMatch(admin,/service.role|service_role|SUPABASE_SERVICE_ROLE/,'No privileged key in browser script');
assert.match(css,/\.tso-admin-page/,'Dashboard responsive styling present');
console.log('TSO2 owner admin routing, settings, and secure RPC integration: static checks passed.');
