import assert from 'node:assert/strict';
import fs from 'node:fs';
const app=fs.readFileSync('tso2/app.js','utf8');
const auth=fs.readFileSync('tso2/auth.js','utf8');
const html=fs.readFileSync('tso2/index.html','utf8');
assert.match(auth,/async loadNotifications\(limit=24\)/,'Per-user saved inbox interface');
assert.match(auth,/\.from\('notifications'\)/,'Uses existing notifications table');
assert.match(auth,/\.eq\('user_id',user.id\)/,'Queries are scoped to authenticated account');
assert.match(auth,/slate_date\.is\.null,slate_date\.eq\./,'Legacy at-bat alerts filtered to the current slate');
assert.match(auth,/async markNotificationsRead\(ids=null\)/,'Persistent read status is implemented');
assert.match(auth,/\.update\(\{read:true\}\)/,'Read marking is persisted to Supabase');
assert.match(app,/savedAccountNotifications\.slice\(0,4\)/,'Saved alerts and live signals are combined without taking over');
assert.match(app,/window\.TSO_AUTH\.markNotificationsRead\(\)/,'Mark-all persists to the owner account');
assert.match(app,/refreshSavedAccountNotifications\(true\)/,'Verified login refreshes saved inbox');
assert.match(app,/ACCOUNT_NOTIFICATION_REFRESH_MS/,'Polling runs for signed-in accounts');
assert.match(html,/Live signals & saved account alerts/,'Bell identifies persisted account data');
assert.match(html,/data-push-toggle/,'Bell offers background device alerts');
assert.match(html,/data-push-status/,'Bell explains permission and subscription state');
assert.match(html,/push-client\.js/,'Push registration module is loaded');
const worker=fs.readFileSync('tso2/sw.js','utf8');
const push=fs.readFileSync('tso2/push-client.js','utf8');
assert.match(worker,/addEventListener\('push'/,'Service worker handles background pushes');
assert.match(worker,/showNotification\(/,'Incoming push results in a user-visible notification');
assert.match(worker,/addEventListener\('notificationclick'/,'Alert click opens TSO2');
assert.match(worker,/tso2-app-icon-192\.png/,'Push uses the approved TSO2 icon');
assert.match(push,/Notification\.requestPermission\(\)/,'Permission is prompted from a user action');
assert.match(push,/pushManager\.subscribe/,'Browser creates a Web Push subscription');
assert.match(push,/pushManager\.getSubscription/,'Existing device subscription can be inspected');
assert.match(push,/standalone/,'iOS requires installed Home Screen web app');
assert.match(push,/TSO_AUTH\.savePushSubscription/,'Subscription persists to signed-in account');
assert.match(auth,/async getPushSubscription\(endpoint\)/,'Push status is account-scoped');
assert.match(auth,/async savePushSubscription\(subscription\)/,'Push registration persists with Supabase RLS');
assert.match(auth,/async removePushSubscription\(endpoint\)/,'User can opt out of remote push');
assert.match(auth,/\.eq\('user_id',owner\)/,'Push subscriptions are scoped to current user');
assert.doesNotMatch(push,/SUPABASE_SERVICE_ROLE_KEY|VAPID_PRIVATE_KEY/,'Browser never receives server secrets');
assert.doesNotMatch(auth,/const\\s+SUPABASE_SERVICE_ROLE\\s*=|\\bsb_secret_[A-Za-z0-9]+/,'Client must not declare privileged keys');
console.log('TSO2 account inbox + background device push: static checks passed');
